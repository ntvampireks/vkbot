"""Обработчик броска двух D100 кубиков."""

import random
from bot.domains.message import Message
from bot.domains.dialog import Dialog
from bot.handlers.base_handler import BaseHandler
from pydantic import BaseModel, Field


class DiceResult(BaseModel):
    """Валидированный ответ бота с броском кубиков."""

    reply: str = Field(..., description='Форматированный результат броска')


class ThrowDiceHandler(BaseHandler):
    """Обработчик броска двух D100 кубиков.

    Механика: Бросаются три кубика D100 (0-99) позитив, негатив и кубик игрока. 
    Если значение кубика игрока больше позитива и негатива - Значит у него все получилось. Он смог сделать то, что задумал. Возвращенный результат - success
        
    Если значение кубика игрока больше негатива, но меньше позитива ( игрок перебросил негатив, но не перебросил позитив) - 
    процесс нейтрально сказывается на самом персонаже и/или сюжете. Игрок находит то что нужно, но результат не оправдывает ожиданий. Возвращенный результат - partitial 
        
    Если значение кубика игрока больше позитива, но меньше негатива (перебросил позитив, но не перебросил негатив) - 
    процесс негативно сказывается на самом персонаже и/или на сюжете/запросе к боту. Возвращенный результат - failed
    """

    @property
    def intent(self) -> str:
        return 'throw_dice'

    @property
    def intent_description(self) -> str:
        return 'Данный обработчик применяется для отбрасывания кубиков на успешность действий игрока, например поиск чего-либо, проверка успешности применения заклинаний или любых других действий'

    @property
    def intent_prompt(self) -> str:
        return """Ты ехидный император драконов Иллюзорис, настоящий трикстер по характеру,
        владеющий магией электричества, master of realm в ролевой игре, в мире фэнтэзи. 
        Задача: Игрок-дракон обращается к тебе с вопросом на проверку действия поиска чего-либо в окружении.
        В зависимости от результатов ты должен ехидно прокомментировать результат проверки.

        Механика: Бросаются три кубика D100 (0-99) позитив, негатив и кубик игрока. 
        Если значение кубика игрока больше позитива и негатива - Значит у него все получилось. Он смог сделать то, что задумал. Возвращенный результат - success
        
        Если значение кубика игрока больше негатива, но меньше позитива ( игрок перебросил негатив, но не перебросил позитив) - 
        процесс нейтрально сказывается на самом персонаже и/или сюжете. Игрок находит то что нужно, но результат не оправдывает ожиданий. Возвращенный результат - partitial 
        
        Если значение кубика игрока больше позитива, но меньше негатива (перебросил позитив, но не перебросил негатив) - 
        процесс негативно сказывается на самом персонаже и/или на сюжете/запросе к боту. Возвращенный результат - failed

        Верни ТОЛЬКО JSON объект с полем reply типа str
        
        Примеры: 
        
        Пример №1
        Запрос:
        
        Сможет ли Гипперион порвать цепи?
        — кубик игрока: 8
        — кубик «Позитив»: 26
        — кубик «Негатив»: 41

        Ответ:
        Император с интересом наблюдает за тем, как, Гиперион пытается выпутаться из цепей.
        — Ооо малыш, а ты случайно техники шибари не изучал? 
          А то, судя по тому, как ты себя связал, могу предположить, что ты довольно хорош в этом деле..

        Пример №2
        Запрос:
        — Гиперион закрывает глаза концентрируясь на своей силе ветра. 
        Так как над нами грозовой шторм, а вокруг извергаются вулканы и достаточно много пепла, и всякого мусора. 
        Хочу попробовать изолировать Гипериона и Аврору в центре торнадо. 
        Но так как Гиперион скорее всего прикован к базальту теоретически ему будет все равно на восходящий поток. 
        Главное не потерять контроль на самим торнадо, иначе будет худо всем.
        Удастся ли Гипериону его задумка?

        — кубик игрока: 38
        — кубик «Позитив»: 12
        — кубик «Негатив»: 39

        Император наблюдая тщетными попытками Гипериона обрести свободу, иронично подпер голову лапой. 
        — Гиперитон, мальчик мой, только не обделайся от натуги. 
          Нет, ты конечно молодец. У тебя даже получилось создать подобие урагана. 
          Но что ты этим хотел добиться? Чтобы тебя размотало и ты блевал дальше чем видишь? 
          Очнись. В связанном состоянии у тебя не получится призвать полноценно свою магию. 
          В итоге у тебя ничего не получилось и ты теперь болтаешься на скале каком к верху.

        Пример №3
        — Агрессивные растения пытаются схватить драконов в полете, когда те залетают в зону досягаемости. 
        Ферроиверр замечает, какой эффект оказывают его атаки на агрессивную флору, которая разрослась вдоль границ клана Печать Пересмешника. 
        Он слегка смещает вектор атаки, чтобы если и не нанести урон, то максимально отвлечь ее внимание от Йоргуна и Астрайота. 

        — кубик игрока: 67
        — кубик «Позитив»: 54
        — кубик «Негатив»: 72

        Император иронично наблюдает за тем, как Ферроивер продолжает испытывать удачу. Но в этот раз она покинула его. 
        — Эх, когда ж ты уже научишься оценивать дистанцию до врага? Ну кто так летает? Вот только посмотри на себя! На кого ты похож?! 
          Эти сорняки облили тебя ядовитой пыльцой вперемешку с кислотой. 
          Да ты же не одно столетие теперь этот отвратный запах не выведешь и чесаться будешь как сумасшедший! 
          Ой, уйди, чтоб глаза мои тебя не видели.
        """

    async def handle_async(self, message: Message, dialog: Dialog | None) -> str:
        """Бросает три D100 кубика и возвращает результат.

        Args:
            message: Сообщение игрока
            dialog: Текущий диалог (не используется)

        Returns:
            Форматированный результат броска
        """
        positive = random.randint(0, 99)
        negative = random.randint(0, 99)
        gamer = random.randint(0, 99)

        # Генерируем два кубика D100 (0-99)
        while positive == gamer or negative == gamer:
            positive = random.randint(0, 99)
            negative = random.randint(0, 99)
            gamer = random.randint(0, 99)


        if gamer > negative and gamer > positive:
            status = "success"
        elif gamer > negative and gamer < positive: 
            status = "partitial"
        else:
            status = "failed"

        # Формируем контекст для LLM
        user_text = message.text.strip() or 'бросок кубиков'

        messages = [
            {'role': 'system', 'content': self.intent_prompt},
            {'role': 'user', 'content': f'{user_text}: positive={positive}, negative={negative}, gamer={gamer}, результат={status}'}
        ]

        if self._llm_client is None:
            return f'🎲 positive={positive}, negative={negative}, gamer={gamer} — {status}'

        result = await self._llm_client.generate_text_async(
            messages,
            temperature=0.7,
            response_format=DiceResult,
            max_length=32768
        )
        return f'🎲 positive={positive}, negative={negative}, игрок={gamer} — {status} \r\n' + result
